#!/usr/bin/env python3
"""Regenerate the ROM availability catalog from hash-checked dispatch tables."""
from pathlib import Path
import hashlib
import json
import re
import struct

here = Path(__file__).resolve().parent
repo = here.parents[1]
workspace = repo.parent
roms = json.loads((here.parent / 'abi-audit/rom-inventory.json').read_text())
symbols = {int(slot): name for slot, name in re.findall(
    r'^DEFINE_SYSCALL(?:_NEO)?\((\d+),\s*(\w+)\)',
    (repo / 'os3k/syscall.c').read_text(), re.M)}
for rom in roms:
    data = (workspace / rom['path']).read_bytes()
    assert hashlib.sha256(data).hexdigest() == rom['sha256'], rom['path']
    targets = list(struct.unpack_from('>' + 'I' * rom['slots'], data, rom['table_offset']))
    assert targets == rom['targets'], rom['name']

lines = ['# Syscall availability by ROM', '',
    'Generated by `python3 betawise/research/syscalls/catalog-roms.py` from the',
    'hash-checked original images in [the ROM inventory](../abi-audit/rom-inventory.json).',
    'These labels identify inspected images, not every ROM released for a model.', '',
    '`empty` means an in-range zero dispatch entry; `outside table` means the slot',
    'exceeds the declared table length. A hexadecimal address means a populated',
    'entry, **not** proof of useful implementation or a compatible calling convention.',
    'In particular, AS3000 3.01 DrawBitmap (18) is a no-op, and TextEditorSetFonts (183)',
    'is a stub returning `0x02000003`; Neo implementations differ. RasterOp (19)',
    'is empty in both AS3000 3.01 and the Neo 3.01 image, and populated in the Neo 3.21 image.',
    'Symbols track the current clean-room names in syscall.c.', '',
    'No compile-time platform restriction is currently enforced by the headers.', '',
    '| Image | Slots | Image path | SHA-256 |', '|---|---:|---|---|']
for r in roms:
    lines.append(f"| {r['name']} | {r['slots']} | `{r['path']}` | `{r['sha256']}` |")
lines += ['', '| Slot | Opcode | Symbol | AS3000 3.01 | Neo 3.01 | Neo 3.21 |',
          '|---:|---|---|---|---|---|']
for slot in range(max(r['slots'] for r in roms)):
    cells = []
    for r in roms:
        cells.append('outside table' if slot >= r['slots'] else
                     (f"`0x{r['targets'][slot]:08X}`" if r['targets'][slot] else 'empty'))
    lines.append(f"| {slot} | `0x{0xA000 + 4 * slot:04X}` | {symbols.get(slot, '—')} | " + ' | '.join(cells) + ' |')
(here / 'rom-availability.md').write_text('\n'.join(lines) + '\n')
print(f'Cataloged {len(roms)} ROMs and {slot + 1} slots.')
